test('Case data contains 0 strictly simplified Chinese characters', () => {
  const jsonStr = JSON.stringify(CASES);
  const foundSimplified = [];

  for (let i = 0; i < jsonStr.length; i++) {
    const ch = jsonStr[i];
    if (STRICT_SIMPLIFIED_CHARS.has(ch)) {
      foundSimplified.push({
        char: ch,
        context: jsonStr.slice(Math.max(0, i - 12), Math.min(jsonStr.length, i + 13))
      });
    }
  }

  assert.equal(
    foundSimplified.length,
    0,
    `Found ${foundSimplified.length} simplified characters in CASES data:\n` +
      foundSimplified.map(f => `  '${f.char}' in "...${f.context}..."`).join('\n')
  );
});
